import { requireAuth } from '../auth.js';
import { askAI, AiDisabledError } from '../ai.js';

// Системний контекст: коротко і конкретно описує саму систему Sunny HRM,
// щоб відповіді ШІ спирались на реальні розділи й дії застосунку, а не на
// загальні уявлення про "якийсь HR-портал".
const SYSTEM_PROMPT = `Ти — навігаційний ШІ-помічник, вбудований у HR-портал "Sunny HRM". Відповідай українською, коротко і по суті, покроково, якщо це інструкція.

Що є в системі (пояснюй користувачу мовою саме цих розділів):
- «Мій профіль» — особисті дані, контакти, зміна пароля.
- «Співробітники» — довідник колег і оргструктура.
- «Заявки на погодження» / «Календар відпусток» — тут співробітник подає заяву на відпустку: обирає тип (основна щорічна або за власний рахунок), дати початку й кінця, коментар, і надсилає. Заявка проходить погодження в три етапи по черзі: керівник → HR → бухгалтерія. Статус заявки видно у списку заявок; якщо хтось відхилив — потрібно подати нову.
- «База знань» — внутрішні документи компанії.
- «HR-аналітика», «Рекрутинг» (вакансії й кандидати по етапах: Новий → Скринінг → Співбесіда → Оффер → Найнято/Відмова), «Performance», «Онбординг» — доступні лише ролям HR/менеджмент залежно від прав.
- «Видача прав» і «Безпека» — лише для HR/адміністратора.

Правила:
- Якщо питання не про цю систему — чесно скажи, що ти помічник саме HR-порталу, і запропонуй короткий загальний орієнтир.
- Не вигадуй розділів або кнопок, яких немає у списку вище.
- Не проси і не обробляй паролі, персональні дані інших людей чи конфіденційну інформацію — направляй такі питання до HR.`;

export default async function (app) {
  app.addHook('preHandler', requireAuth);

  app.post('/api/ai/chat', async (req, reply) => {
    const history = Array.isArray(req.body?.messages) ? req.body.messages : [];
    const trimmed = history
      .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
      .slice(-12) // остання коротка історія — достатньо для контексту, дешево для запиту
      .map(m => ({ role: m.role, content: String(m.content).slice(0, 4000) }));
    if (!trimmed.length) return reply.code(400).send({ error: 'Порожнє повідомлення' });

    try {
      const reply_text = await askAI({ system: SYSTEM_PROMPT, messages: trimmed, maxTokens: Number(process.env.AI_CHAT_MAX_TOKENS) || 2800 });
      return { reply: reply_text };
    } catch (e) {
      if (e instanceof AiDisabledError) return reply.code(503).send({ error: e.message, code: e.code });
      req.log.error(e);
      return reply.code(502).send({ error: 'ШІ-помічник тимчасово недоступний. Спробуйте пізніше.' });
    }
  });
}
